"""slicer.main() without PrusaSlicer: a fake slicer writes the G-code that the checks read."""

import json
import re
import zipfile

import pytest

from linux3d import slicer
from linux3d.export import PLAN, m600_metadata
from linux3d.slicer import CONFIG_ENTRY, M600_ENTRY, main, plan_entry, stored_colour_changes

PROFILE_COLOUR = "#FF8000"  # filament_colour of the Prusament PETG profile
CHANGES = [[1.4, "white"], [2.2, "black"]]
ZNURT = {"start": "violet", "changes": CHANGES}


def _export(folder, plan, changes=CHANGES):
    """A plate with `changes` for each name in plan, and plan.json, as export writes them."""
    folder.mkdir(parents=True, exist_ok=True)
    for name in plan:
        with zipfile.ZipFile(folder / f"{name}.3mf", "w") as z:
            z.writestr("3D/3dmodel.model", "<model/>")
            z.writestr(M600_ENTRY, m600_metadata([tuple(c) for c in changes]))
    (folder / PLAN).write_text(json.dumps(plan), encoding="utf-8")


@pytest.fixture
def fake_slicer(monkeypatch):
    """Replace PrusaSlicer. The G-code has an M600 at each height stored in the 3MF and a
    config block with the colour of --filament-colour, else the project's colour if it
    slices a project, else the profile's orange. `options` breaks parts of this to make
    the checks fail."""
    options = {"takes_colour": True, "reads_project": True}

    def fake(cmd, plate, gcode, material="petg", extra=()):
        with zipfile.ZipFile(plate) as z:
            names = z.namelist()
            m600 = z.read(M600_ENTRY).decode() if M600_ENTRY in names else ""
            project = z.read(CONFIG_ENTRY).decode() if CONFIG_ENTRY in names else ""
        found = re.search(r"^; filament_colour = (.*)$", project, re.MULTILINE)
        colour = PROFILE_COLOUR
        if "--filament-colour" in extra and options["takes_colour"]:
            colour = extra[extra.index("--filament-colour") + 1]
        elif found and options["reads_project"]:
            colour = found.group(1)
        moves = "".join(f";Z:{z}\nM600\n" for z in re.findall(r'print_z="([\d.]+)"', m600))
        gcode.write_text(
            "; generated by PrusaSlicer 2.9.6\n" + moves
            + "; estimated printing time (normal mode) = 19m 20s\n; filament used [g] = 6.63\n"
            + f"; prusaslicer_config = begin\n; binary_gcode = 0\n; filament_colour = {colour}\n"
            + f"; printer_settings_id = {slicer.PRINTER}\n; prusaslicer_config = end\n",
            encoding="utf-8")

    monkeypatch.setattr(slicer, "slice_plate", fake)
    monkeypatch.setattr(slicer, "prusaslicer_command", lambda: ["prusa-slicer"])
    return options


def _project_colour(folder, name):
    with zipfile.ZipFile(folder / "projects" / f"{name}.3mf") as z:
        config = z.read(CONFIG_ENTRY).decode()
    return re.search(r"^; filament_colour = (.*)$", config, re.MULTILINE).group(1)


def _result(capsys, name="znurt"):
    """The line that main() printed for the plate."""
    return next(line for line in capsys.readouterr().out.splitlines()
                if line.startswith(name + " "))


def test_project_starts_in_the_colour_of_the_design(tmp_path, fake_slicer, capsys):
    """The project's filament colour is the plate's start filament from plan.json, not the
    orange of the profile, and the slice of the project reads it back."""
    _export(tmp_path, {"znurt": ZNURT})
    assert main(tmp_path) == 0
    assert _project_colour(tmp_path, "znurt") == "#5E4A9C"
    assert _result(capsys).endswith("OK")


@pytest.mark.parametrize("option, found", [("takes_colour", "#FF8000"),
                                           ("reads_project", "#FF8000")])
def test_colour_that_does_not_reach_the_project_is_reported(tmp_path, fake_slicer, capsys,
                                                            option, found):
    """A PrusaSlicer that ignores --filament-colour, or a project that does not load it."""
    fake_slicer[option] = False
    _export(tmp_path, {"znurt": ZNURT})
    assert main(tmp_path) == 1
    assert _result(capsys).endswith(f"project starts in {found}, the design in #5E4A9C")


def test_colour_changes_in_the_wrong_colours_are_reported(tmp_path, fake_slicer, capsys):
    """Right heights, swapped colours: the 3MF must give each M600 the design's colour."""
    _export(tmp_path, {"znurt": ZNURT}, changes=[[1.4, "black"], [2.2, "white"]])
    assert main(tmp_path) == 1
    line = _result(capsys)
    assert ("3MF stores Z 1.40 -> #1C1A1E, Z 2.20 -> #ECE8DC, "
            "the design says Z 1.40 -> #ECE8DC, Z 2.20 -> #1C1A1E") in line
    assert "expected M600" not in line  # the heights are right


@pytest.mark.parametrize("plan, message", [
    ({}, "not in plan.json: export it again, or delete the plate if no export makes it "
         "any more"),
    ({"znurt": {"start": "violet"}}, "incomplete entry in plan.json: export again"),
    ({"znurt": {"start": "pink", "changes": CHANGES}}, "unknown filament pink in plan.json"),
])
def test_plate_the_plan_cannot_describe_gives_one_clear_problem(tmp_path, fake_slicer,
                                                                capsys, plan, message):
    """No guesses about the colour changes: one problem that says what to do, and no false
    M600 problems next to it."""
    _export(tmp_path, {"znurt": ZNURT})
    (tmp_path / PLAN).write_text(json.dumps(plan or {"other": ZNURT}), encoding="utf-8")
    assert main(tmp_path) == 1
    line = _result(capsys)
    assert line.endswith(message) and "M600 at [" not in line and "3MF stores" not in line
    assert _project_colour(tmp_path, "znurt") == PROFILE_COLOUR


def test_plan_from_an_older_export_still_checks_the_colour_changes(tmp_path, fake_slicer,
                                                                   capsys):
    """An older plan.json has only the colour changes: slice checks them, keeps the
    profile's colour and says what to do (a plate no export makes any more stays stale)."""
    _export(tmp_path, {"znurt": CHANGES})
    assert main(tmp_path) == 1
    line = _result(capsys)
    assert line.endswith("plan.json has no start filament: export it again, or delete the "
                         "plate if no export makes it any more")
    assert "3MF stores" not in line and "expected M600" not in line
    assert _project_colour(tmp_path, "znurt") == PROFILE_COLOUR


def test_plan_entry():
    assert plan_entry({"p": ZNURT}, "p") == ("#5E4A9C", [(1.4, "#ECE8DC"), (2.2, "#1C1A1E")], [])


def test_stored_colour_changes(tmp_path):
    _export(tmp_path, {"p": ZNURT})
    assert stored_colour_changes(tmp_path / "p.3mf") == [(1.4, "#ECE8DC"), (2.2, "#1C1A1E")]
